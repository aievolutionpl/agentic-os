import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import React,{act} from 'react';
import {createRoot} from 'react-dom/client';
import assert from 'node:assert/strict';
await build({entryPoints:['src/renderer/VoiceInput.tsx'],bundle:true,platform:'node',format:'esm',external:['react','react-dom','lucide-react'],outfile:'.runtime/voice-test.mjs'});
const dom=new JSDOM('<div id="root"></div>',{url:'http://localhost'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,IS_REACT_ACT_ENVIRONMENT:true});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
let stopped=0,calls=[],texts=[];
Object.defineProperty(navigator,'mediaDevices',{value:{getUserMedia:async()=>({getTracks:()=>[{stop:()=>stopped++}]})}});
globalThis.MediaRecorder=class {state='inactive';start(){this.state='recording';}stop(){this.state='inactive';this.ondataavailable({data:new Blob(['audio'])});this.onstop();}};
window.agenting={voiceBegin:async()=>true,voiceTranscribe:async input=>{calls.push(input);return 'Próba mikrofonu';}};
const {VoiceInput}=await import('../.runtime/voice-test.mjs');
globalThis.localStorage=window.localStorage;
const root=createRoot(document.getElementById('root'));
await act(async()=>root.render(React.createElement(VoiceInput,{pl:true,onText:text=>texts.push(text)})));
const key=async(type,code)=>act(async()=>window.dispatchEvent(new window.KeyboardEvent(type,{code,bubbles:true,cancelable:true})));
await key('keydown','F8');assert.match(document.body.textContent,/Nagrywanie/);
await key('keyup','F8');assert.equal(calls[0].language,'pl');assert.equal(calls[0].model,'base');assert.equal(texts[0],'Próba mikrofonu');assert.equal(stopped,1);
localStorage.setItem('agenting-voice-v1',JSON.stringify({language:'en',model:'tiny',shortcut:'F9'}));
await act(async()=>window.dispatchEvent(new window.Event('agenting-voice-settings')));
await key('keydown','F8');assert.equal(calls.length,1);
await key('keydown','F9');await act(async()=>window.dispatchEvent(new window.Event('blur')));
assert.equal(calls[1].language,'en');assert.equal(calls[1].model,'tiny');assert.equal(stopped,2);
let resolveMedia;
navigator.mediaDevices.getUserMedia=()=>new Promise(resolve=>resolveMedia=resolve);
await key('keydown','F9');await key('keyup','F9');
await act(async()=>resolveMedia({getTracks:()=>[{stop:()=>stopped++}]}));
assert.equal(calls.length,2);assert.equal(stopped,3);assert.doesNotMatch(document.body.textContent,/Nagrywanie/);
await act(async()=>root.unmount());
console.log('PASS: Polish/base default, hold/release, language/model/shortcut changes, blur stop, early release cleanup');
