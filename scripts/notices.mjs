import {
  readFileSync,
  writeFileSync,
  readdirSync,
  existsSync,
  mkdirSync,
} from "node:fs";
import { join } from "node:path";
mkdirSync("licenses/dependencies", { recursive: true });
const inventory = [];
function visit(dir) {
  for (const file of readdirSync(dir, { withFileTypes: true })) {
    if (!file.isDirectory() || file.name.startsWith(".")) continue;
    const path = join(dir, file.name);
    if (file.name.startsWith("@")) {
      visit(path);
      continue;
    }
    const meta = join(path, "package.json");
    if (!existsSync(meta)) continue;
    const p = JSON.parse(readFileSync(meta, "utf8"));
    const key = `${p.name.replaceAll("/", "_")}-${p.version}`;
    const notices = readdirSync(path).filter((f) =>
      /^(licen[cs]e|copying|notice)([._-]|$)/i.test(f),
    );
    const copied = [];
    for (const n of notices) {
      try {
        const target = `dependencies/${key}-${n}`;
        // Normalize line endings only; preserve upstream license text.
        writeFileSync(
          join("licenses", target),
          readFileSync(join(path, n), "utf8").replace(/\r\n/g, "\n"),
        );
        copied.push(target);
      } catch {}
    }
    // Upstream memory tarballs omit LICENSE even though package metadata points to it.
    // Keep the original repository text in our release; never relabel mixed licenses.
    const fallback = p.name === "@lobehub/icons-static-svg" ? "lobe-icons-LICENSE" : p.name === "@modelcontextprotocol/server-memory" ? "mcp-servers-LICENSE"
      : p.name.startsWith("@modelcontextprotocol/") ? "mcp-typescript-sdk-LICENSE" : null;
    if (!copied.length && fallback && existsSync(join("licenses/upstream", fallback))) copied.push(`upstream/${fallback}`);
    inventory.push({
      name: p.name,
      version: p.version,
      license: p.license ?? "UNKNOWN",
      notices: copied,
    });
    if (existsSync(join(path, "node_modules")))
      visit(join(path, "node_modules"));
  }
}
visit("node_modules");
writeFileSync(
  "licenses/inventory.json",
  JSON.stringify(inventory, null, 2) + "\n",
);
writeFileSync(
  "licenses/THIRD_PARTY_NOTICES.md",
  "# Third-party dependencies\n\nInstalled metadata and original license/notice texts retained in dependencies/. No reference application code copied. Generated by node scripts/notices.mjs. Electron runtime also includes Chromium LICENSES.chromium.html; retain it when distributing. This inventory is not a vulnerability or release compliance certification.\n\n" +
    inventory
      .map(
        (p) =>
          `- ${p.name} ${p.version}: ${p.license}; ${p.notices.length ? p.notices.map((n) => `[notice](${n})`).join(", ") : "NOTICE REVIEW REQUIRED"}`,
      )
      .join("\n") +
    "\n",
);
console.log(
  `Preserved license texts for ${inventory.length} installed packages`,
);
